/* ============================================================
   my.adhd for iOS — handing the wallpaper to Shortcuts

   Only Shortcuts can set a wallpaper, so the automation is the last step
   and this is what feeds it. The shortcut is "my.adhd Lock Screen",
   generated by tools/shortcut/build.py:

       Triggers: sunrise, my.adhd is closed, a notification from my.adhd
         -> my.adhd wallpaper mode       (WallpaperModeIntent, below)
              "skip" -> stop here; nothing moved since the last one
         -> Update my.adhd wallpaper     (this intent, returns a PNG)
         -> Set Wallpaper Photo          (Apple's, Lock Screen, no preview)
              "redraw" -> set again on the wallpaper that came back,
                          and switch to it
              "home"   -> my.adhd home screen (WallpaperHomeIntent), set on
                          the Home Screen of that same wallpaper
         -> Confirm my.adhd wallpaper    (WallpaperConfirmIntent, below)

   The last step is what lets the app say "working" and mean it. The
   first one only proves a picture was drawn; Shortcuts stops at the first
   action that fails, so reaching the confirm step proves Set Wallpaper
   Photo succeeded too.

   Two things about this intent are load-bearing.

   openAppWhenRun is false. The whole point is that it runs at seven in
   the morning without bringing an app to the front, which means it runs
   with no scene, no window and no web view — and therefore cannot ask the
   page anything. It reads the keychain snapshot the app left behind
   instead. That is why TaskSnapshot came first.

   It never clears the wallpaper. Every failure throws, and a throw leaves
   whatever is on the lock screen where it is. A phone rebooted overnight
   and not yet unlocked cannot open the keychain at all
   (kSecAttrAccessibleAfterFirstUnlock), and yesterday's wallpaper is a
   great deal better than a blank one.
   ============================================================ */

import AppIntents
import SwiftUI
import UniformTypeIdentifiers

struct WallpaperIntent: AppIntent {
    static var title: LocalizedStringResource = "Update my.adhd wallpaper"
    static var description = IntentDescription(
        "Draws your matrix as a picture and hands it back, for Set Wallpaper Photo to put on the lock screen."
    )

    /// The reason this exists at all. See the note at the top.
    static var openAppWhenRun: Bool = false

    @MainActor
    func perform() async throws -> some IntentResult & ReturnsValue<IntentFile> {
        /* The store the app writes, read the way the matrix screen reads
           it, with anything ticked on a widget since laid over it. Without
           the overlay a task ticked at ten last night is still NOW on the
           seven o'clock lock screen, because the app has not been opened
           to drain the tick yet. WallpaperBoard.swift says why this is not
           the widgets' snapshot. */
        guard let board = WallpaperBoard.current() else { throw WallpaperError.noData }
        let url = try Wallpaper.render(board)
        return .result(value: try Self.handOver(url, as: "myadhd-lock.png"))
    }

    /* The bytes, not the file. Handed a file URL, Shortcuts opens the
       file itself, from its own process, inside this app's container —
       and with the phone locked that came back empty: "Unable to Set
       Wallpaper. Please provide an image", three times over, on a
       device on 2026-10-26, while the same run unlocked worked. Read
       here, in this process, the picture travels with the result. */
    static func handOver(_ url: URL, as name: String) throws -> IntentFile {
        let data = try Data(contentsOf: url)
        return IntentFile(data: data, filename: name, type: .png)
    }
}

/// The shortcut's first step: skip, set or redraw, as WallpaperMode
/// decides. The shortcut branches on the text, so the app can change what
/// a run does without anybody reinstalling the shortcut.
///
/// An unreadable board answers "set", never "skip" — the run goes on to
/// WallpaperIntent, which throws, and yesterday's picture stays put.
struct WallpaperModeIntent: AppIntent {
    static var title: LocalizedStringResource = "my.adhd wallpaper mode"
    static var description = IntentDescription(
        "Put this first. It says whether your lock screen needs drawing again: skip, set or redraw."
    )
    static var openAppWhenRun: Bool = false

    @MainActor
    func perform() async throws -> some IntentResult & ReturnsValue<String> {
        /* The run has started, so the notification that started it has
           done its job: take it down now, a second after it arrived,
           rather than at the end — a skip or a failure never reaches the
           confirm step, and it would sit on the lock screen. */
        WallpaperPing.clear()
        let mode = WallpaperMode.decide(
            digest: WallpaperBoard.current().flatMap(Wallpaper.digest(of:)),
            lastDrawn: Wallpaper.lastDrawnDigest,
            lastRun: Wallpaper.lastRun,
            lastConfirmed: Wallpaper.lastConfirmed,
            forceRedraw: Wallpaper.forceRedraw)
        return .result(value: WallpaperMode.answer(mode, lockOnly: Wallpaper.style.lockOnly))
    }
}

/// The Home Screen half, for Lock Screen only: the ground with no boxes.
/// The shortcut sets it on the Home Screen of the wallpaper it has just
/// set, when the mode says " home". No Siri phrase, like the confirm.
struct WallpaperHomeIntent: AppIntent {
    static var title: LocalizedStringResource = "my.adhd home screen"
    static var description = IntentDescription(
        "Your wallpaper's photo without the matrix, for the Home Screen, so the matrix stays on the lock screen only."
    )
    static var openAppWhenRun: Bool = false

    @MainActor
    func perform() async throws -> some IntentResult & ReturnsValue<IntentFile> {
        let url = try Wallpaper.renderHome()
        return .result(value: try WallpaperIntent.handOver(url, as: "myadhd-home.png"))
    }
}

/// The shortcut's last step. It does nothing but note the time — and it
/// only ever runs once Set Wallpaper Photo before it has succeeded, which
/// is the whole of its value: the Lock Screen Display page reads this
/// stamp, not the drawing one, to say the automation works.
///
/// No Siri phrase and no place in `MyADHDShortcuts`: it means nothing on
/// its own, and Shortcuts lists every app action in its library anyway.
struct WallpaperConfirmIntent: AppIntent {
    static var title: LocalizedStringResource = "Confirm my.adhd wallpaper"
    static var description = IntentDescription(
        "Put this last, after Set Wallpaper Photo. It tells my.adhd your lock screen was really updated."
    )
    static var openAppWhenRun: Bool = false

    @MainActor
    func perform() async throws -> some IntentResult {
        Wallpaper.markConfirmed()
        WallpaperPing.clear()
        return .result()
    }
}

/// The same picture, for anyone who would rather drive it from the Photos
/// app or check it by hand. Opens the app on the setup sheet, which is
/// where the preview and the instructions are.
struct WallpaperSetupIntent: AppIntent {
    static var title: LocalizedStringResource = "Set up my.adhd wallpaper"
    static var description = IntentDescription("Opens the wallpaper instructions and a preview of your own.")
    static var openAppWhenRun: Bool = true

    @MainActor
    func perform() async throws -> some IntentResult {
        Inbox.openWallpaperSetup()
        return .result()
    }
}
